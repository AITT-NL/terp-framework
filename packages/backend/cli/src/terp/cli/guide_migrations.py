"""The ``terp guide migrations`` topic: per-package histories, and running them safely."""

from __future__ import annotations

TOPIC = """\
Database migrations (terp migrate)

- Each table-owning package (capability or app module) owns an INDEPENDENT, linear
  Alembic history with its own alembic_version_<label> table - no shared graph and no
  CROSS-package merges. Terp discovers them; you never hand-write env.py.
- Author a revision after changing a model (autogenerated, scoped to that package so
  it never proposes another package's tables):
      terp migrate make <label> -m "add invoice.status"   # <label> e.g. invoices
  Autogenerate DIFFS A LIVE DATABASE AT HEAD, so it needs two things the default
  environment does not give you: a database that outlives the process (the settings
  default is in-memory SQLite) and one that is already at head (a fresh file database
  is behind). Both, in one paste, with a throwaway file you delete afterwards:
      DATABASE_URL="sqlite:///./.migrate-scratch.db" terp migrate upgrade
      DATABASE_URL="sqlite:///./.migrate-scratch.db" terp migrate make <label>
  (PowerShell: $env:DATABASE_URL='sqlite:///./.migrate-scratch.db')
  Point it at your real Postgres URL instead when the revision must diff against real
  schema, or pass --no-autogenerate to author an empty revision by hand.
  Cross-module / cross-package foreign keys just work: every package's models are
  imported so an FK target (a sibling module, or identity_user) resolves at make time,
  and upgrade is ordered by FK dependencies so a referenced table is always created
  before the table that references it - regardless of label ordering. (A cross-package
  FK *cycle* cannot be ordered and fails closed; break it with a nullable FK populated
  in a later migration.)
- Apply / inspect / walk back across every package:
      terp migrate upgrade                 # each package to head (run on deploy)
      terp migrate upgrade --sql > release.sql   # DBA-reviewable SQL; connects nothing, flat
      terp migrate status                  # current-vs-head per package
      terp migrate check                   # exit 0 only at head or inside the window
      terp migrate graph                   # revisions and parents as Alembic loads them
      terp migrate downgrade               # every package back to base (or -N)
      terp migrate downgrade --label notes --revision <rev>   # one package only
  A concrete revision is package-specific, so the all-package downgrade takes only
  base or a relative -N; pass --label to roll one package to any of its own revisions.
  A downgrade is for walking a history back while developing. A production rollback
  never migrates (next point).
- ROLLING BACK A RELEASE (ADR 0185). Each revision says whether it is expand-only:
      expand_only = True    # the previous release still runs on the schema this leaves
  `terp migrate make` always writes `expand_only = False` (a contract revision), and adds
  a comment where every operation it generated is on the expand list. Raise the mark
  yourself, once the previous release may run without what the revision adds: a NOT NULL
  scan state with a default, or a token epoch, is on the list and still carries a
  restriction a rollback would drop. The expand list is closed: create_table (a key from
  it only with CASCADE or SET NULL, never onto a soft-deleted table) and bulk_insert into
  it; add_column that is nullable, has a server_default or is Computed, with no unique, no
  check and at most a SET NULL key on a nullable column; create_index that is not unique;
  a batch block of those, never recreate="always". Anything else (a drop, a rename,
  tightening, execute(), a statement through op.get_bind(), a back-fill of an existing
  table) is refused by `terp check` (expand_revisions_only_expand, no opt-out) and again
  by the migration run, before its DDL. A back-fill runs as a job: the expand release
  already handles rows it has not filled.
  When every revision release N applied is expand-only, release N-1 starts again on N's
  database: its boot guard admits a database one migration run ahead (it logs which
  revisions it runs behind), and its `migrate` finds nothing to apply and runs no DDL. The
  rollback check is the target's own `terp migrate check`, run from the target's image
  against the live database: exit 0 is restore-free, anything else is a restore. Two
  expanding releases in a row are one too many, a contract revision or another Terp
  version is never crossed, and a migration applied from an offline script is not in
  the record, so each of those rolls back by restore.
  Until the contract release, N keeps writing the old shape N-1 reads, treats it as the
  truth for what N-1 writes (compute a derived value on read, or make it a generated
  column), and handles NULL in its new columns.
  Every release after a rollback keeps N's revision files and the model fields and tables
  they create, and reverts behaviour only; removing them is a later contract release. A
  release cut from N-1 that adds a revision of its own is refused by `migrate`.
- CONTRACT STEPS GO INTO A LATER RELEASE than the one that expanded: drop, rename or
  tighten once nothing in the release before still needs the old shape. A release that
  mixes expand and contract revisions is legal and rolls back by restore.
- Removing a module or capability from the app RETIRES it, in the same release: list its
  label in <app root>/modules/__init__.py, read without importing the app,
      RETIRED_MIGRATIONS = ("invoices",)
  a literal tuple of strings (anything else refuses). Its tables stay yours. A package
  that comes back takes a new label.
- Two developers branched the same package? Resolve the within-package divergence:
      terp migrate heads                   # more than one head = diverged
      terp migrate merge <label> -m "merge"
  Before a release, re-parent one unreleased revision onto the other instead: a merge
  revision is a contract revision.
- Locks: `migrate` runs before `api` is recreated, so the previous release still serves
  while it runs. A create_index without postgresql_concurrently (inside
  op.get_context().autocommit_block()), a volatile default and a generated column (stored,
  so the table is rewritten) hold a lock that long; on a large table compute a derived
  value on read. A new child table of a soft-deleted parent is a contract revision:
  neither CASCADE nor SET NULL can fire onto it.
- A STEP THAT IS SAFE ONLY AGAINST AN EMPTY DATABASE is refused by `terp check`
  (`no_destructive_migrations`). A deploy migrates while the previous release still
  serves, and a rollback runs that release on the migrated schema, so a revision has two
  audiences your scratch database never shows: the rows production holds, and the
  release still running. Five kinds of step fail one of them:
      drop         drop_table / drop_column / TRUNCATE / DELETE FROM / DROP SCHEMA
      rename       rename_table / alter_column(new_column_name=...) / ALTER TABLE .. RENAME
      type change  alter_column(type_=...) / ALTER COLUMN .. TYPE
      NOT NULL     alter_column(nullable=False) on an existing table / SET NOT NULL
      constraint   create_unique_constraint / create_check_constraint /
                   create_foreign_key / create_primary_key / create_index(unique=True) /
                   ADD CONSTRAINT / CREATE UNIQUE INDEX / VALIDATE CONSTRAINT
  on `op`, a batch block or any alias, imported by name (from alembic.op import
  drop_column) or looked up by a literal getattr, in upgrade() and in every function of
  the revision it calls, and through execute(...) whenever the statement is readable in
  the source, one statement at a time. Do this instead, and every finding says which:
  EXPAND (add the new column, nullable, or the new table beside the old one), BACKFILL
  (copy or clean the rows with a job, not a statement in the revision, and write both),
  then CONTRACT in a LATER release (drop the old name, tighten, add the constraint). The
  contract step is the destructive one, so it carries
  `# arch-allow-no-destructive-migrations: <reason>` on (or immediately above) its line,
  after review, budgeted by the escape-hatch ratchet. Not refused: anything on a table
  this upgrade() creates (it holds no rows yet), and a unique, foreign-key or
  unique-index constraint on columns this upgrade() adds nullable with no server_default
  (every existing row holds NULL, which those accept) - the shape autogenerate writes for
  a new reference column. Not refused is not the same as an expand step: a constraint on
  an existing table, or any execute(), is never one. A type WIDENING is still reported,
  because nothing in the revision says what the old type was: justify it with the marker.
- ADDING A NOT NULL COLUMN is the revision that passes everything you can run and then
  fails in production. For a new non-nullable field autogenerate writes
  `add_column(sa.Column('rank', sa.Integer(), nullable=False))`, and that statement
  succeeds against an empty database and fails against one that holds rows - the rows
  already there need a value it never supplies. Nothing local catches it, because a
  migration test upgrades a FRESH scratch database, where the statement is correct.
  Give the column a server_default and the database back-fills the existing rows as it
  adds it; new rows still take the model-side default:
      op.add_column('note', sa.Column('rank', sa.Integer(), nullable=False,
                                      server_default='0'))
  Where no literal default is right, expand/contract instead - add the column nullable,
  back-fill it with a job in the same release, tighten it in a LATER release (that
  tightening is a contract step: it takes the destructive-migration marker above). `terp check`
  refuses the unbackfilled form (`not_null_columns_are_backfilled`); a table that
  genuinely holds no rows yet opts out with
  `# arch-allow-not-null-columns-are-backfilled: <reason>`.
- MOVING A MODEL TO ANOTHER MODULE is the one edit that looks free and is not. Just
  moving the class emits NO ddl at all - the losing package stops owning the table so
  its scoped autogenerate cannot propose a drop, and the gaining package diffs against
  a database where the table already exists so it proposes no create. Your database
  keeps upgrading; CI and staging stay green. Then the NEXT ordinary change to that
  model (an added column) is authored into the gaining package's INDEPENDENT history,
  which - with no foreign key between the two packages - a fresh install may run
  BEFORE the history that creates the table: "no such table", months later, in a new
  environment, blamed on an innocent add_column. Terp refuses the split at `terp
  migrate make` and in the build-time guard. Move a table properly, expand/contract:
      1. Give the new module its own model with its own __tablename__;
         `terp migrate make <new>` creates it.
      2. Copy the rows in that same release (a data migration, or a backfill job),
         and write to both tables while the old one still has readers.
      3. In a LATER release, once nothing reads the old table, drop it - with
         `# arch-allow-no-destructive-migrations: <reason>` and a human reviewer.
  Step 3 stays human-reviewed on purpose: dropping a populated table is a genuine,
  irreversible risk, and the one place where a second pair of eyes is worth the
  friction. If the model is simply in the wrong module and holds no data you care
  about, the cheap fix is to move the class BACK and rename the module instead.
  Already shipped the move and planning the expand/contract for a later release? The
  owning package's models.py may carry `# arch-allow-table-ownership-is-not-split:
  <reason>`, counted by the escape-hatch budget like any other opt-out.
- Adopt Terp on an EXISTING database (built by create_all or by hand) without dropping
  data - baseline each history at head, then only genuinely new migrations apply:
      terp migrate stamp                   # records head, runs no DDL
- Want physical per-module separation on PostgreSQL (each package's tables in its own
  schema, the groundwork for per-schema GRANTs)? Set DB_SCHEMA_LAYOUT=per-module for a
  fresh database, or move an existing flat one in place (idempotent, data moves with
  the tables, version tables stay put):
      terp migrate adopt-schemas           # one-time; ADR 0070
- Least-privilege runtime (ADR 0071): migrate as the owning role, run the app as a
  separate login that holds ONLY DML - the database itself then refuses DDL and
  (per-module) any tampering with migration state. Provision the login yourself, then:
      terp migrate grant-runtime <role>    # idempotent; run after upgrade/adopt
  Run it as the role that runs `terp migrate` - or pass --owner-role <role> so the
  ALTER DEFAULT PRIVILEGES it emits covers tables that future upgrades create.
  It also revokes EXECUTE from PUBLIC on the functions, procedures, aggregates and
  window functions in those schemas, by name and as the owner's default for later
  ones: a SECURITY DEFINER function runs as its owner, also when an aggregate calls it.
  Triggers keep firing; an extension's functions are left to the extension. A
  statement that reaches one of the app's own functions, wherever the call sits (the
  statement, a view, a column default, a generated column, an index expression, a check,
  a policy, or a trigger function), then needs it granted to the runtime role, which
  grant-runtime does not do; a grant made by hand survives a re-run:
      GRANT EXECUTE ON FUNCTION <schema>.<name>(<args>) TO <role>;
  A routine PUBLIC may execute that the running role may not revoke (another role owns
  it) makes grant-runtime refuse, changing nothing: run it as that owner, or give the
  routine to the migration owner.
  Module-to-module DML is deliberately NOT database-blocked (one runtime role spans
  every write schema; audit/outbox ride the business write's single session).
- Operate safely: run `terp migrate upgrade` ONCE per deploy (e.g. a release job), not
  on every replica - it takes no lock, so concurrent runs race. The boot guard below is
  read-only and safe on every replica. The migration engine is built from DATABASE_URL,
  so put URL-expressible options (e.g. sslmode) there.
- Run from your app root so app/ is importable (app modules ship their history in
  app/modules/<name>/migrations/; a capability declares a terp.migrations entry point).
- Make upgrading non-optional: wire the fail-closed boot guard so the app refuses to
  start against a stale schema (a deploy that skipped the upgrade fails loudly). Pass an
  app_root so it guards your app modules too, not only capabilities:
      from functools import partial
      from pathlib import Path
      from terp.migrations import assert_migrations_current
      create_app(specs, ..., migration_check=partial(
          assert_migrations_current, app_root=Path(__file__).parent))
  Gate it on production if local dev builds the schema with create_all / SQLite.
- Test the REAL migration path (not only create_all) so a model change with no
  migration fails CI, not production:
      from terp.migrations import upgrade, assert_migrations_match_models
      upgrade(db_url, app_root); assert_migrations_match_models(db_url, app_root)
"""
