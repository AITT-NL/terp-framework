"""``terp verify`` refuses a cross-platform ``node_modules`` with a directive message.

An npm install is platform-specific: the native binaries a bundler needs are optional
dependencies gated on ``os``/``cpu``. A tree installed on a Windows host contains no
Linux binary, so running the gate in the container died with a raw Node stack
(``Cannot find module '@rolldown/binding-linux-x64-gnu'``) that named neither the
cause nor the fix — the one thing every Terp failure is supposed to do.

The lockfile already records which optional package belongs on which platform, so the
detection is exact and needs no maintained list of native package names.
"""

from __future__ import annotations

import json
import pathlib
import shlex
import sys

_REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
_CLI_SRC = _REPO_ROOT / "packages" / "backend" / "cli" / "src"
sys.path.insert(0, str(_CLI_SRC))

from terp.cli.verify import (  # noqa: E402
    _node_libc,
    _node_modules_problem,
    _node_platform,
    _npm_workspace,
    _run_subprocess,
    VerifyCheck,
)


def _workspace(root: pathlib.Path, name: str, lock_packages: dict) -> pathlib.Path:
    """An installed npm tree at *name*, with a lockfile declaring *lock_packages*."""
    directory = root / name
    (directory / "node_modules").mkdir(parents=True)
    (directory / "package.json").write_text("{}", encoding="utf-8")
    (directory / "package-lock.json").write_text(
        json.dumps({"packages": lock_packages}), encoding="utf-8"
    )
    return directory


def _frontend(root: pathlib.Path, lock_packages: dict) -> pathlib.Path:
    return _workspace(root, "frontend", lock_packages)


def test_a_project_without_a_frontend_is_not_diagnosed(tmp_path: pathlib.Path) -> None:
    assert _node_modules_problem(tmp_path, "frontend") is None


def test_a_missing_node_modules_names_the_install_command(
    tmp_path: pathlib.Path,
) -> None:
    (tmp_path / "frontend").mkdir()
    (tmp_path / "frontend" / "package.json").write_text("{}", encoding="utf-8")

    problem = _node_modules_problem(tmp_path, "frontend")

    assert problem is not None
    assert "npm --prefix frontend ci" in problem


def test_a_tree_without_a_lockfile_is_not_diagnosed(tmp_path: pathlib.Path) -> None:
    # The diagnosis is derived from the lockfile's os/cpu gates. With no lockfile there
    # is nothing to be exact about, and guessing would be worse than staying quiet.
    frontend = tmp_path / "frontend"
    (frontend / "node_modules").mkdir(parents=True)
    (frontend / "package.json").write_text("{}", encoding="utf-8")

    assert _node_modules_problem(tmp_path, "frontend") is None


def test_a_tree_installed_elsewhere_is_reported_with_the_fix(
    tmp_path: pathlib.Path,
) -> None:
    system, arch = _node_platform()
    _frontend(
        tmp_path,
        {
            "": {"name": "app"},
            "node_modules/@rolldown/binding-here": {"os": [system], "cpu": [arch]},
        },
    )

    problem = _node_modules_problem(tmp_path, "frontend")

    assert problem is not None
    assert "different platform" in problem
    assert "@rolldown/binding-here" in problem
    assert f"{system}/{arch}" in problem
    assert "npm --prefix frontend ci" in problem


def test_a_package_constrained_to_another_platform_is_absent_by_design(
    tmp_path: pathlib.Path,
) -> None:
    # The whole point of the os/cpu gate: a Linux binary is *supposed* to be missing
    # on Windows. Flagging it would make the check cry wolf on every healthy install.
    system, _ = _node_platform()
    other = "darwin" if system != "darwin" else "linux"
    _frontend(
        tmp_path,
        {
            "": {"name": "app"},
            "node_modules/@rolldown/binding-elsewhere": {"os": [other]},
        },
    )

    assert _node_modules_problem(tmp_path, "frontend") is None


def test_a_platform_neutral_package_is_not_a_platform_verdict(
    tmp_path: pathlib.Path,
) -> None:
    # A missing package with no os/cpu constraint means the install is incomplete or
    # stale — a different problem with a different fix, so this check stays silent
    # rather than blaming the platform for it.
    _frontend(tmp_path, {"": {"name": "app"}, "node_modules/typescript": {}})

    assert _node_modules_problem(tmp_path, "frontend") is None


def test_a_healthy_install_is_silent(tmp_path: pathlib.Path) -> None:
    system, arch = _node_platform()
    frontend = _frontend(
        tmp_path,
        {
            "": {"name": "app"},
            "node_modules/@rolldown/binding-here": {"os": [system], "cpu": [arch]},
        },
    )
    (frontend / "node_modules" / "@rolldown" / "binding-here").mkdir(parents=True)

    assert _node_modules_problem(tmp_path, "frontend") is None


def test_the_other_libc_flavour_is_absent_by_design(
    tmp_path: pathlib.Path,
) -> None:
    # A Linux bundler ships a -gnu *and* a -musl binding for the same os/cpu, and npm
    # installs exactly one of them. Reading only os/cpu reported the flavour this
    # machine does not use as missing, turning every healthy container tree red.
    system, arch = _node_platform()
    libc = _node_libc(system)
    other = "musl" if libc != "musl" else "glibc"
    _frontend(
        tmp_path,
        {
            "": {"name": "app"},
            "node_modules/@rolldown/binding-other-libc": {
                "os": [system],
                "cpu": [arch],
                "libc": [other],
            },
        },
    )

    problem = _node_modules_problem(tmp_path, "frontend")

    # Off Linux npm ignores libc entirely, so there the entry is a genuine absence.
    assert problem is None if libc is not None else "different platform" in problem


def test_libc_is_read_on_linux_and_nowhere_else() -> None:
    # npm applies the libc gate on Linux only, so asking anywhere else would invent a
    # constraint that npm never enforces.
    assert _node_libc("win32") is None
    assert _node_libc("darwin") is None
    assert _node_libc("linux") in {"glibc", "musl"}


def test_a_corrupt_lockfile_does_not_become_a_platform_verdict(
    tmp_path: pathlib.Path,
) -> None:
    frontend = tmp_path / "frontend"
    (frontend / "node_modules").mkdir(parents=True)
    (frontend / "package.json").write_text("{}", encoding="utf-8")
    (frontend / "package-lock.json").write_text("{not json", encoding="utf-8")

    assert _node_modules_problem(tmp_path, "frontend") is None


def test_an_npm_check_fails_with_the_diagnosis_instead_of_running_node(
    tmp_path: pathlib.Path,
) -> None:
    # The diagnosis has to replace the raw Node stack, not accompany it: by the time
    # npm has spawned, the reader is already looking at a module-resolution trace.
    system, arch = _node_platform()
    _frontend(
        tmp_path,
        {
            "": {"name": "app"},
            "node_modules/@rolldown/binding-here": {"os": [system], "cpu": [arch]},
        },
    )
    check = VerifyCheck(
        id="frontend-build",
        category="frontend-build",
        command="npm --prefix frontend run build",
    )

    exit_code, output = _run_subprocess(check, tmp_path)

    assert exit_code == 1
    assert "different platform" in output
    assert "Cannot find module" not in output


def test_a_non_npm_check_is_not_gated_on_node_modules(tmp_path: pathlib.Path) -> None:
    # A broken frontend install must not fail the backend lanes; each check reports
    # its own health or the verdict stops meaning anything.
    system, arch = _node_platform()
    _frontend(
        tmp_path,
        {
            "": {"name": "app"},
            "node_modules/@rolldown/binding-here": {"os": [system], "cpu": [arch]},
        },
    )
    check = VerifyCheck(
        id="probe",
        category="probe",
        command=f"{pathlib.Path(sys.executable).as_posix()} -c pass",
    )

    exit_code, _ = _run_subprocess(check, tmp_path)

    assert exit_code == 0


def test_the_workspace_is_read_from_the_prefix_in_either_spelling() -> None:
    assert _npm_workspace(shlex.split("npm --prefix conformance test")) == "conformance"
    assert _npm_workspace(shlex.split("npm --prefix=conformance test")) == "conformance"
    assert _npm_workspace(shlex.split("npm --prefix frontend run build")) == "frontend"


def test_an_npm_command_without_a_prefix_is_the_project_root() -> None:
    # The profile is open at the app end (ADR 0106), so an app may declare its own npm
    # check; one with no prefix runs in the root `_run_subprocess` passes as cwd.
    assert _npm_workspace(shlex.split("npm test")) == "."
    # A dangling or empty prefix is npm's own usage error to report. Inventing a
    # directory nobody named would refuse the check for the wrong reason.
    assert _npm_workspace(shlex.split("npm test --prefix")) == "."
    assert _npm_workspace(shlex.split("npm --prefix= test")) == "."


def test_a_missing_conformance_tree_is_diagnosed_instead_of_reaching_node(
    tmp_path: pathlib.Path,
) -> None:
    # The half of the hole that used to reach Node. `conformance/` was never looked
    # at, so a missing tree passed the precondition and died on the raw
    # module-resolution trace this function exists to replace. Note there is no
    # `frontend/` here at all, which is what made the old guard return None.
    (tmp_path / "conformance").mkdir()
    (tmp_path / "conformance" / "package.json").write_text("{}", encoding="utf-8")
    check = VerifyCheck(
        id="conformance",
        category="conformance",
        command="npm --prefix conformance test",
    )

    exit_code, output = _run_subprocess(check, tmp_path)

    assert exit_code == 1
    assert "conformance/node_modules is missing" in output
    assert "npm --prefix conformance ci" in output
    assert "frontend" not in output
    assert "Cannot find module" not in output


def test_an_installed_tree_is_not_refused_for_a_sibling_it_never_uses(
    tmp_path: pathlib.Path,
) -> None:
    # The other half: `--only conformance` refused until `frontend/` was installed,
    # in a job with no other use for it. The suite is Playwright specs in
    # `conformance/` driving the workbench over HTTP; the frontend is served by a
    # container built from its own tree, so the two are unrelated.
    _workspace(tmp_path, "conformance", {"": {"name": "conformance"}})
    (tmp_path / "frontend").mkdir()
    (tmp_path / "frontend" / "package.json").write_text("{}", encoding="utf-8")

    argv = shlex.split("npm --prefix conformance test")

    assert _node_modules_problem(tmp_path, _npm_workspace(argv)) is None
    # ...and the frontend tree it does not use is genuinely unusable, so the pass
    # above is the workspace derivation and not an accident of an empty fixture.
    assert _node_modules_problem(tmp_path, "frontend") is not None


def test_a_cross_platform_tree_names_the_workspace_it_was_read_in(
    tmp_path: pathlib.Path,
) -> None:
    system, arch = _node_platform()
    _workspace(
        tmp_path,
        "conformance",
        {
            "": {"name": "conformance"},
            "node_modules/@playwright/binding-here": {"os": [system], "cpu": [arch]},
        },
    )

    problem = _node_modules_problem(tmp_path, "conformance")

    assert problem is not None
    assert "conformance/node_modules was installed for a different platform" in problem
    assert "npm --prefix conformance ci" in problem
    assert "frontend" not in problem


def test_a_root_workspace_names_the_unprefixed_install_command(
    tmp_path: pathlib.Path,
) -> None:
    # `./node_modules`, `npm --prefix . ci` and "the . checks" would all read as a typo.
    (tmp_path / "package.json").write_text("{}", encoding="utf-8")

    problem = _node_modules_problem(tmp_path, ".")

    assert problem is not None
    assert problem.startswith("node_modules is missing")
    assert "the root npm checks cannot run" in problem
    assert "Fix: npm ci" in problem
    assert "--prefix" not in problem
